async def connect_authorized(
    client: TelegramClient,
    phone: str,
    login_code_file: Optional[str],
) -> None:
    await client.connect()

    if await client.is_user_authorized():
        return

    await client.send_code_request(phone)

    if login_code_file:
        code = read_login_code_from_file(Path(login_code_file))
    else:
        code = input("Enter Telegram login code: ").strip()

    try:
        await client.sign_in(phone=phone, code=code)
    except SessionPasswordNeededError:
        password = os.getenv("TG_2FA_PASSWORD") or getpass("Telegram 2FA password: ")
        await client.sign_in(password=password)


async def resolve_or_join(client: TelegramClient, ref: ParsedTelegramRef, should_join: bool) -> Any:
    if ref.invite_hash:
        if not should_join:
            raise RuntimeError("Private invite links require --join")

        try:
            updates = await client(ImportChatInviteRequest(ref.invite_hash))
            chats = getattr(updates, "chats", None) or []
            if not chats:
                raise RuntimeError("Joined invite but no chat entity returned.")
            return chats[0]
        except UserAlreadyParticipantError as exc:
            raise RuntimeError(
                "Already joined private invite. Use the public @username/link if available, "
                "or open the group once in Telegram Desktop and pass its visible name."
            ) from exc
        except (InviteHashExpiredError, InviteHashInvalidError) as exc:
            raise RuntimeError(f"Invalid or expired invite: {ref.original}") from exc

    if ref.public_ref is None:
        raise RuntimeError(f"Could not parse Telegram ref: {ref.original}")

    entity = await client.get_entity(ref.public_ref)

    if should_join:
        try:
            await client(JoinChannelRequest(entity))
            await asyncio.sleep(1.0)
        except UserAlreadyParticipantError:
            pass

    return await client.get_entity(ref.public_ref)


async def get_member_count(client: TelegramClient, entity: Any) -> Optional[int]:
    try:
        full = await client(GetFullChannelRequest(entity))
        count = getattr(full.full_chat, "participants_count", None)
        return int(count) if count is not None else None
    except RPCError:
        return None


async def get_admin_sender_hashes(
    client: TelegramClient,
    entity: Any,
    salt: str,
    enabled: bool,
) -> set[str]:
    if not enabled:
        return set()

    admin_hashes: set[str] = set()
    try:
        admins = await client.get_participants(entity, filter=lambda x: x)
        # The lambda filter is not guaranteed to produce admins only across Telethon versions.
        # Fallback below: keep empty if this generic call does not expose participant admin flags.
        for user in admins:
            participant = getattr(user, "participant", None)
            is_admin = participant is not None and participant.__class__.__name__.lower().endswith("admin")
            if is_admin and getattr(user, "id", None) is not None:
                admin_hashes.add(hash_sender(int(user.id), salt) or "")
    except Exception:
        # Admin detection is optional. Never fail collection because of it.
        return set()

    return {x for x in admin_hashes if x}


def make_group_key(entity: Any) -> str:
    peer_id = getattr(entity, "id", None)
    if peer_id is None:
        raise RuntimeError("Missing Telegram peer id.")
    return str(peer_id)


