def utc_now() -> datetime:
    return datetime.now(timezone.utc)


def parse_iso_utc(value: Optional[str]) -> Optional[datetime]:
    if not value:
        return None
    cleaned = value.strip().replace("Z", "+00:00")
    dt = datetime.fromisoformat(cleaned)
    return to_utc(dt)


def to_utc(dt: datetime) -> datetime:
    return dt.replace(tzinfo=timezone.utc) if dt.tzinfo is None else dt.astimezone(timezone.utc)


def require_env(name: str) -> str:
    value = os.getenv(name)
    if not value:
        raise RuntimeError(f"Missing {name}. Check your .env file.")
    return value.strip().strip('"').strip("'")


def safe_div(a: float, b: float) -> float:
    return a / b if b else 0.0


def clamp(x: float, lo: float = 0.0, hi: float = 100.0) -> float:
    return max(lo, min(hi, x))


def sha256_hex(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def hash_sender(sender_id: Optional[int], salt: str) -> Optional[str]:
    if sender_id is None:
        return None
    return sha256_hex(f"{salt}:sender:{sender_id}")


def normalize_text(text: str) -> str:
    text = text.lower()
    text = URL_RE.sub(" URL ", text)
    text = SOLANA_ADDR_RE.sub(" ADDRESS ", text)
    text = WHITESPACE_RE.sub(" ", text).strip()
    return text


def text_hash(text: str, salt: str) -> Optional[str]:
    norm = normalize_text(text)
    if not norm:
        return None
    return sha256_hex(f"{salt}:text:{norm[:1_000]}")


def emoji_char_count(text: str) -> int:
    # Broad but deterministic approximation. Good enough as a spam/raid feature.
    count = 0
    for ch in text:
        cat = unicodedata.category(ch)
        name = unicodedata.name(ch, "")
        if cat in {"So", "Sk"} and (
            "EMOJI" in name
            or "FACE" in name
            or "HEART" in name
            or "ROCKET" in name
            or "FIRE" in name
            or "HAND" in name
            or "CIRCLE" in name
            or "SQUARE" in name
        ):
            count += 1
    return count


def shannon_entropy(text: str) -> float:
    cleaned = WHITESPACE_RE.sub("", text.lower())
    if not cleaned:
        return 0.0
    counts = Counter(cleaned)
    n = len(cleaned)
    return -sum((c / n) * math.log2(c / n) for c in counts.values())


def extract_domains(text: str) -> set[str]:
    return {m.group(1).lower() for m in DOMAIN_RE.finditer(text)}


def keyword_hits(text: str) -> dict[str, int]:
    hits = {
        name: sum(len(pattern.findall(text)) for pattern in patterns)
        for name, patterns in COMPILED_KEYWORDS.items()
    }
    hits["question"] += text.count("?")
    return hits


def classify_trade_alert(text: str) -> tuple[int, str, int]:
    """
    Returns (is_trade_alert, side, score).

    Conservative enough to avoid classifying every human "buy" message as a bot alert.
    A message must look templated: buy/sell action plus market/tx context, numbers, or links.
    """
    if not text:
        return 0, "none", 0

    buy = bool(TRADE_BUY_RE.search(text))
    sell = bool(TRADE_SELL_RE.search(text))
    action = buy or sell
    context = bool(TRADE_CONTEXT_RE.search(text))
    numeric = bool(TRADE_NUMERIC_RE.search(text))
    link = bool(URL_RE.search(text))
    ca = bool(SOLANA_ADDR_RE.search(text))

    score = int(action) + int(context) + int(numeric) + int(link) + int(ca)

    is_alert = int(action and score >= 3)
    if not is_alert:
        return 0, "none", score

    if buy and not sell:
        side = "buy"
    elif sell and not buy:
        side = "sell"
    else:
        side = "unknown"

    return 1, side, score


def parse_telegram_ref(value: str) -> ParsedTelegramRef:
    raw = value.strip()

    if raw.startswith("@"):
        return ParsedTelegramRef(raw, raw[1:], None)

    if raw.startswith("t.me/"):
        raw = "https://" + raw

    if raw.startswith("https://t.me/") or raw.startswith("http://t.me/"):
        parsed = urlparse(raw)
        path = parsed.path.strip("/")

        if path.startswith("+"):
            return ParsedTelegramRef(value, None, path[1:])

        if path.startswith("joinchat/"):
            return ParsedTelegramRef(value, None, path.split("/", 1)[1])

        if not path:
            raise ValueError(f"Invalid Telegram link: {value}")

        return ParsedTelegramRef(value, path.split("/")[0], None)

    return ParsedTelegramRef(value, raw, None)


def read_login_code_from_file(path: Path) -> str:
    if not path.exists():
        raise RuntimeError(f"Login code file does not exist: {path}")
    code = path.read_text(encoding="utf-8").strip()
    path.unlink(missing_ok=True)
    if not code:
        raise RuntimeError(f"Login code file is empty: {path}")
    return code


