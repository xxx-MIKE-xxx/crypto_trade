def message_to_row(
    group_key: str,
    msg: Message,
    salt: str,
    store_raw_text: bool,
    admin_sender_hashes: set[str],
) -> Optional[tuple[Any, ...]]:
    if msg.id is None or msg.date is None:
        return None

    text = msg.message or ""
    sender_hash = hash_sender(getattr(msg, "sender_id", None), salt)
    trade_flag, trade_side, trade_score = classify_trade_alert(text)
    hits = keyword_hits(text)
    domains = extract_domains(text)
    emoji_count = emoji_char_count(text)

    has_media = int(getattr(msg, "media", None) is not None)
    is_sticker_only = int(not text.strip() and getattr(msg, "sticker", None) is not None)

    return (
        group_key,
        int(msg.id),
        to_utc(msg.date).isoformat(),
        sender_hash,
        int(sender_hash in admin_sender_hashes if sender_hash else False),
        text if store_raw_text else None,
        text_hash(text, salt),
        len(text),
        shannon_entropy(text),
        emoji_count,

        trade_flag,
        trade_side,
        trade_score,

        int(bool(URL_RE.search(text))),
        len(domains),
        has_media,
        is_sticker_only,
        int(getattr(msg, "reply_to_msg_id", None) is not None),
        int(bool(BOT_COMMAND_RE.search(text.strip()))),
        int(bool(SOLANA_ADDR_RE.search(text))),
        int(bool(CASHTAG_RE.search(text))),

        hits["buy_intent"],
        hits["sell_intent"],
        hits["hodl"],
        hits["conviction"],
        hits["community"],
        hits["execution"],
        hits["trust_claim"],
        hits["fud"],
        hits["panic"],
        hits["technical_issue"],
        hits["raid"],
        hits["call_group"],
        hits["question"],
        len(RAID_TEMPLATE_RE.findall(text)),

        int(getattr(msg, "views", None) or 0),
        int(getattr(msg, "forwards", None) or 0),
    )


def save_message(conn: sqlite3.Connection, row: tuple[Any, ...]) -> bool:
    before = conn.total_changes
    conn.execute(
        """
        INSERT OR IGNORE INTO tg_messages (
            group_key, message_id, ts_utc, sender_hash, is_admin, raw_text,
            text_hash, text_len, text_entropy, emoji_chars,
            is_trade_alert, trade_side, trade_alert_score,
            has_link, domain_count, has_media, is_sticker_only, is_reply,
            is_command, has_ca, has_cashtag,
            buy_intent_hits, sell_intent_hits, hodl_hits, conviction_hits,
            community_hits, execution_hits, trust_claim_hits, fud_hits,
            panic_hits, technical_issue_hits, raid_hits, call_group_hits,
            question_hits, raid_template_hits, views, forwards
        )
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """,
        row,
    )
    return conn.total_changes > before


async def backfill(
    client: TelegramClient,
    conn: sqlite3.Connection,
    entity: Any,
    group_key: str,
    salt: str,
    store_raw_text: bool,
    admin_sender_hashes: set[str],
    history_days: int,
    full_history: bool,
    limit: Optional[int],
) -> int:
    since = None if full_history else utc_now() - timedelta(days=history_days)
    inserted = 0
    scanned = 0

    async for msg in client.iter_messages(entity, limit=limit):
        if msg.date is None:
            continue

        msg_dt = to_utc(msg.date)
        if since is not None and msg_dt < since:
            break

        row = message_to_row(group_key, msg, salt, store_raw_text, admin_sender_hashes)
        if row is None:
            continue

        if save_message(conn, row):
            inserted += 1

        scanned += 1

        if scanned % 500 == 0:
            conn.commit()
            print(f"backfill scanned={scanned:,} inserted={inserted:,}")
            await asyncio.sleep(1.0)

    conn.commit()
    return inserted


