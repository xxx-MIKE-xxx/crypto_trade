def fetch_window_rows(
    conn: sqlite3.Connection,
    group_key: str,
    lookback_minutes: int,
    end_time: Optional[datetime] = None,
) -> list[sqlite3.Row]:
    end = end_time or utc_now()
    since = end - timedelta(minutes=lookback_minutes)

    return conn.execute(
        """
        SELECT *
        FROM tg_messages
        WHERE group_key = ?
          AND ts_utc >= ?
          AND ts_utc <= ?
        """,
        (group_key, since.isoformat(), end.isoformat()),
    ).fetchall()


def sender_first_seen_map(
    conn: sqlite3.Connection,
    group_key: str,
    sender_hashes: set[str],
) -> dict[str, datetime]:
    if not sender_hashes:
        return {}

    placeholders = ",".join("?" for _ in sender_hashes)
    query = f"""
        SELECT sender_hash, MIN(ts_utc) AS first_seen
        FROM tg_messages
        WHERE group_key = ?
          AND sender_hash IN ({placeholders})
        GROUP BY sender_hash
    """

    rows = conn.execute(query, [group_key, *sender_hashes]).fetchall()
    return {
        str(row["sender_hash"]): parse_iso_utc(str(row["first_seen"])) or utc_now()
        for row in rows
    }


def compute_second_bursts(rows: list[sqlite3.Row], threshold: int) -> int:
    per_second: Counter[str] = Counter()
    for row in rows:
        ts = parse_iso_utc(str(row["ts_utc"]))
        if ts is not None:
            per_second[ts.replace(microsecond=0).isoformat()] += 1
    return sum(1 for count in per_second.values() if count >= threshold)


def compute_retention_5m_to_30m(
    conn: sqlite3.Connection,
    group_key: str,
    end_time: Optional[datetime],
) -> float:
    end = end_time or utc_now()
    recent_start = end - timedelta(minutes=5)
    earlier_start = end - timedelta(minutes=30)

    recent = conn.execute(
        """
        SELECT DISTINCT sender_hash
        FROM tg_messages
        WHERE group_key = ?
          AND is_trade_alert = 0
          AND sender_hash IS NOT NULL
          AND ts_utc >= ?
          AND ts_utc <= ?
        """,
        (group_key, recent_start.isoformat(), end.isoformat()),
    ).fetchall()

    earlier = conn.execute(
        """
        SELECT DISTINCT sender_hash
        FROM tg_messages
        WHERE group_key = ?
          AND is_trade_alert = 0
          AND sender_hash IS NOT NULL
          AND ts_utc >= ?
          AND ts_utc < ?
        """,
        (group_key, earlier_start.isoformat(), recent_start.isoformat()),
    ).fetchall()

    recent_set = {str(r["sender_hash"]) for r in recent}
    earlier_set = {str(r["sender_hash"]) for r in earlier}
    return safe_div(len(recent_set & earlier_set), len(recent_set))


def compute_admin_response_latency_after_fud(
    rows: list[sqlite3.Row],
) -> Optional[float]:
    """
    Median seconds from a FUD/panic/question message to the next admin reply/message.
    Window-local approximation.
    """
    sorted_rows = sorted(rows, key=lambda r: str(r["ts_utc"]))
    event_times: list[datetime] = []
    admin_times: list[datetime] = []

    for row in sorted_rows:
        ts = parse_iso_utc(str(row["ts_utc"]))
        if ts is None:
            continue
        if int(row["is_admin"]) == 1:
            admin_times.append(ts)
        elif (
            int(row["fud_hits"]) > 0
            or int(row["panic_hits"]) > 0
            or int(row["question_hits"]) > 0
        ):
            event_times.append(ts)

    if not event_times or not admin_times:
        return None

    latencies: list[float] = []
    admin_idx = 0
    for event_time in event_times:
        while admin_idx < len(admin_times) and admin_times[admin_idx] < event_time:
            admin_idx += 1
        if admin_idx < len(admin_times):
            latencies.append((admin_times[admin_idx] - event_time).total_seconds())

    if not latencies:
        return None

    latencies.sort()
    mid = len(latencies) // 2
    if len(latencies) % 2:
        return latencies[mid]
    return (latencies[mid - 1] + latencies[mid]) / 2.0


def compute_window_features(
    conn: sqlite3.Connection,
    group_key: str,
    lookback_minutes: int,
    member_count: Optional[int],
    end_time: Optional[datetime],
    migration_time: Optional[datetime],
    burst_threshold: int,
) -> dict[str, Any]:
    rows = fetch_window_rows(conn, group_key, lookback_minutes, end_time=end_time)

    total_msgs = len(rows)
    trade_rows = [r for r in rows if int(r["is_trade_alert"]) == 1]
    human_rows = [r for r in rows if int(r["is_trade_alert"]) == 0]

    trade_msgs = len(trade_rows)
    human_msgs = len(human_rows)

    sender_counts = Counter(str(r["sender_hash"]) for r in human_rows if r["sender_hash"])
    text_counts = Counter(str(r["text_hash"]) for r in human_rows if r["text_hash"])

    unique_human_senders = len(sender_counts)
    top_sender_share = safe_div(max(sender_counts.values()), human_msgs) if sender_counts else 0.0
    top_5_sender_share = safe_div(sum(c for _, c in sender_counts.most_common(5)), human_msgs)
    sender_hhi = sum((count / human_msgs) ** 2 for count in sender_counts.values()) if human_msgs else 0.0
    effective_senders = safe_div(1.0, sender_hhi)

    duplicate_human = sum(c - 1 for c in text_counts.values() if c > 1)
    copy_paste_cluster_count = sum(1 for c in text_counts.values() if c > 1)

    human_sender_set = set(sender_counts.keys())
    first_seen = sender_first_seen_map(conn, group_key, human_sender_set)
    end = end_time or utc_now()
    new_sender_cutoff = end - timedelta(minutes=lookback_minutes)
    new_senders = {s for s, ts in first_seen.items() if ts >= new_sender_cutoff}
    returning_senders = human_sender_set - new_senders

    new_sender_msgs = sum(
        count for sender, count in sender_counts.items() if sender in new_senders
    )
    returning_sender_msgs = sum(
        count for sender, count in sender_counts.items() if sender in returning_senders
    )

    buy_alerts = sum(1 for r in trade_rows if r["trade_side"] == "buy")
    sell_alerts = sum(1 for r in trade_rows if r["trade_side"] == "sell")
    unknown_trade_alerts = sum(1 for r in trade_rows if r["trade_side"] == "unknown")

    # Human keyword sums.
    sums: dict[str, int] = {}
    for col in [
        "buy_intent_hits", "sell_intent_hits", "hodl_hits", "conviction_hits",
        "community_hits", "execution_hits", "trust_claim_hits", "fud_hits",
        "panic_hits", "technical_issue_hits", "raid_hits", "call_group_hits",
        "question_hits", "raid_template_hits",
    ]:
        sums[col] = sum(int(r[col]) for r in human_rows)

    positive_terms = (
        sums["buy_intent_hits"]
        + sums["hodl_hits"]
        + sums["conviction_hits"]
        + sums["community_hits"]
        + sums["execution_hits"]
    )
    negative_terms = (
        sums["sell_intent_hits"]
        + sums["fud_hits"]
        + sums["panic_hits"]
        + sums["technical_issue_hits"]
    )

    human_reply_ratio = safe_div(sum(int(r["is_reply"]) for r in human_rows), human_msgs)
    human_link_ratio = safe_div(sum(int(r["has_link"]) for r in human_rows), human_msgs)
    human_media_ratio = safe_div(sum(int(r["has_media"]) for r in human_rows), human_msgs)
    human_command_ratio = safe_div(sum(int(r["is_command"]) for r in human_rows), human_msgs)
    avg_text_len = safe_div(sum(int(r["text_len"]) for r in human_rows), human_msgs)
    avg_entropy = safe_div(sum(float(r["text_entropy"]) for r in human_rows), human_msgs)
    emoji_char_ratio = safe_div(
        sum(int(r["emoji_chars"]) for r in human_rows),
        sum(max(int(r["text_len"]), 1) for r in human_rows),
    )
    sticker_only_ratio = safe_div(sum(int(r["is_sticker_only"]) for r in human_rows), human_msgs)
    unique_url_domains = len(
        {
            domain
            for r in human_rows
            for domain in extract_domains(str(r["raw_text"] or ""))
        }
    )

    admin_msgs = sum(int(r["is_admin"]) for r in human_rows)
    admin_reply_msgs = sum(1 for r in human_rows if int(r["is_admin"]) and int(r["is_reply"]))

    admin_active_after_migration: Optional[float] = None
    if migration_time is not None:
        admin_after = [
            r for r in human_rows
            if int(r["is_admin"]) == 1
            and (parse_iso_utc(str(r["ts_utc"])) or datetime.min.replace(tzinfo=timezone.utc)) >= migration_time
        ]
        admin_active_after_migration = float(bool(admin_after))

    content_balance = safe_div(positive_terms - negative_terms, human_msgs)
    positive_rate = safe_div(positive_terms, human_msgs)
    negative_rate = safe_div(negative_terms, human_msgs)

    trade_alert_share = safe_div(trade_msgs, total_msgs)
    active_sender_ratio = safe_div(unique_human_senders, member_count or 0)
    organic_attention = (
        safe_div(human_msgs, lookback_minutes)
        * math.log1p(unique_human_senders)
        * (1.0 - top_sender_share)
        * (1.0 - safe_div(duplicate_human, human_msgs))
    )

    # Heuristic score is not a model. It is useful for live ranking/debugging.
    survival_quality_score = clamp(
        10.0
        + min(safe_div(human_msgs, lookback_minutes) / 2.0, 1.0) * 15.0
        + min(safe_div(active_sender_ratio, 0.08), 1.0) * 15.0
        + min(safe_div(effective_senders, 20.0), 1.0) * 15.0
        + min(safe_div(human_reply_ratio, 0.25), 1.0) * 8.0
        + min(max(content_balance, 0.0) / 0.50, 1.0) * 15.0
        + min(safe_div(sums["execution_hits"] + sums["trust_claim_hits"], human_msgs) / 0.20, 1.0) * 7.0
        - min(safe_div(trade_alert_share, 0.70), 1.0) * 10.0
        - top_sender_share * 12.0
        - safe_div(duplicate_human, human_msgs) * 10.0
        - min(safe_div(negative_rate, 0.30), 1.0) * 18.0
        - min(safe_div(sums["technical_issue_hits"], human_msgs) / 0.10, 1.0) * 10.0
    )

    return {
        "lookback_minutes": lookback_minutes,
        "member_count": member_count,

        # Activity split.
        "total_msgs": total_msgs,
        "human_msgs": human_msgs,
        "trade_alert_msgs": trade_msgs,
        "trade_alert_share": trade_alert_share,
        "human_to_trade_msg_ratio": safe_div(human_msgs, trade_msgs),

        # Trade alert / volume-proxy metrics.
        "buy_alerts": buy_alerts,
        "sell_alerts": sell_alerts,
        "unknown_trade_alerts": unknown_trade_alerts,
        "buy_sell_alert_ratio": safe_div(buy_alerts + 1, sell_alerts + 1),
        "trade_alerts_per_min": safe_div(trade_msgs, lookback_minutes),

        # Human breadth.
        "human_msgs_per_min": safe_div(human_msgs, lookback_minutes),
        "unique_human_senders": unique_human_senders,
        "active_human_sender_ratio": active_sender_ratio,
        "human_effective_senders": effective_senders,
        "human_sender_hhi": sender_hhi,
        "human_top_sender_share": top_sender_share,
        "human_top_5_sender_share": top_5_sender_share,
        "new_sender_share": safe_div(len(new_senders), unique_human_senders),
        "returning_sender_share": safe_div(len(returning_senders), unique_human_senders),
        "new_sender_msg_share": safe_div(new_sender_msgs, human_msgs),
        "returning_sender_msg_share": safe_div(returning_sender_msgs, human_msgs),
        "active_retention_5m_to_30m": compute_retention_5m_to_30m(conn, group_key, end_time),

        # Human conversation quality.
        "human_reply_ratio": human_reply_ratio,
        "human_link_ratio": human_link_ratio,
        "human_media_ratio": human_media_ratio,
        "human_command_ratio": human_command_ratio,
        "human_avg_text_len": avg_text_len,
        "unique_url_domains": unique_url_domains,

        # Intent keyword rates.
        "buy_intent_hits": sums["buy_intent_hits"],
        "sell_intent_hits": sums["sell_intent_hits"],
        "hodl_hits": sums["hodl_hits"],
        "conviction_hits": sums["conviction_hits"],
        "community_hits": sums["community_hits"],
        "execution_hits": sums["execution_hits"],
        "trust_claim_hits": sums["trust_claim_hits"],
        "fud_hits": sums["fud_hits"],
        "panic_hits": sums["panic_hits"],
        "technical_issue_hits": sums["technical_issue_hits"],
        "raid_hits": sums["raid_hits"],
        "call_group_hits": sums["call_group_hits"],
        "question_hits": sums["question_hits"],

        "buy_intent_rate": safe_div(sums["buy_intent_hits"], human_msgs),
        "sell_intent_rate": safe_div(sums["sell_intent_hits"], human_msgs),
        "hodl_rate": safe_div(sums["hodl_hits"], human_msgs),
        "conviction_rate": safe_div(sums["conviction_hits"], human_msgs),
        "community_rate": safe_div(sums["community_hits"], human_msgs),
        "execution_rate": safe_div(sums["execution_hits"], human_msgs),
        "trust_claim_rate": safe_div(sums["trust_claim_hits"], human_msgs),
        "fud_rate": safe_div(sums["fud_hits"], human_msgs),
        "panic_rate": safe_div(sums["panic_hits"], human_msgs),
        "technical_issue_rate": safe_div(sums["technical_issue_hits"], human_msgs),
        "raid_rate": safe_div(sums["raid_hits"], human_msgs),
        "call_group_rate": safe_div(sums["call_group_hits"], human_msgs),
        "question_rate": safe_div(sums["question_hits"], human_msgs),

        "bull_bear_ratio": safe_div(
            sums["buy_intent_hits"] + sums["hodl_hits"] + sums["conviction_hits"] + 1,
            sums["sell_intent_hits"] + sums["fud_hits"] + sums["panic_hits"] + sums["technical_issue_hits"] + 1,
        ),
        "positive_term_rate": positive_rate,
        "negative_term_rate": negative_rate,
        "content_balance": content_balance,

        # Spam / raid quality.
        "human_duplicate_text_ratio": safe_div(duplicate_human, human_msgs),
        "copy_paste_cluster_count": copy_paste_cluster_count,
        "avg_message_entropy": avg_entropy,
        "emoji_char_ratio": emoji_char_ratio,
        "sticker_only_ratio": sticker_only_ratio,
        "same_second_burst_count": compute_second_bursts(human_rows, burst_threshold),
        "raid_template_score": safe_div(sums["raid_template_hits"], human_msgs),

        # Admin/dev metrics, optional depending on admin detection.
        "admin_msg_share": safe_div(admin_msgs, human_msgs),
        "admin_reply_ratio": safe_div(admin_reply_msgs, admin_msgs),
        "admin_active_after_migration": admin_active_after_migration,
        "admin_response_latency_after_fud_sec": compute_admin_response_latency_after_fud(human_rows),

        # Live ranking/debug score.
        "organic_attention": organic_attention,
        "survival_quality_score_heuristic": survival_quality_score,
    }


def add_cross_window_features(snapshots: list[dict[str, Any]]) -> dict[str, Any]:
    by_w = {int(s["lookback_minutes"]): s for s in snapshots}
    out: dict[str, Any] = {}

    if 5 in by_w and 60 in by_w:
        out["human_activity_accel_5m_vs_60m"] = safe_div(
            by_w[5]["human_msgs_per_min"],
            by_w[60]["human_msgs_per_min"],
        )
        out["human_breadth_accel_5m_vs_60m"] = safe_div(
            by_w[5]["unique_human_senders"],
            by_w[60]["unique_human_senders"],
        )
        out["risk_rate_accel_5m_vs_60m"] = safe_div(
            by_w[5]["fud_rate"] + by_w[5]["panic_rate"] + by_w[5]["technical_issue_rate"],
            by_w[60]["fud_rate"] + by_w[60]["panic_rate"] + by_w[60]["technical_issue_rate"],
        )
        out["trade_alert_accel_5m_vs_60m"] = safe_div(
            by_w[5]["trade_alerts_per_min"],
            by_w[60]["trade_alerts_per_min"],
        )
        out["content_balance_5m_vs_60m"] = by_w[5]["content_balance"] - by_w[60]["content_balance"]

    if 15 in by_w and 60 in by_w:
        out["human_activity_accel_15m_vs_60m"] = safe_div(
            by_w[15]["human_msgs_per_min"],
            by_w[60]["human_msgs_per_min"],
        )

    if 60 in by_w and 360 in by_w:
        out["human_activity_accel_60m_vs_6h"] = safe_div(
            by_w[60]["human_msgs_per_min"],
            by_w[360]["human_msgs_per_min"],
        )
        out["trade_alert_accel_60m_vs_6h"] = safe_div(
            by_w[60]["trade_alerts_per_min"],
            by_w[360]["trade_alerts_per_min"],
        )
        out["risk_rate_accel_60m_vs_6h"] = safe_div(
            by_w[60]["fud_rate"] + by_w[60]["panic_rate"] + by_w[60]["technical_issue_rate"],
            by_w[360]["fud_rate"] + by_w[360]["panic_rate"] + by_w[360]["technical_issue_rate"],
        )

    return out


def save_snapshot(
    conn: sqlite3.Connection,
    group_key: str,
    input_ref: str,
    entity: Any,
    features: dict[str, Any],
    migration_time: Optional[datetime],
) -> None:
    conn.execute(
        """
        INSERT INTO tg_snapshots (
            group_key, input_ref, title, username, collected_at_utc,
            lookback_minutes, migration_time_utc, features_json
        )
        VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        """,
        (
            group_key,
            input_ref,
            getattr(entity, "title", None),
            getattr(entity, "username", None),
            utc_now().isoformat(),
            int(features["lookback_minutes"]),
            migration_time.isoformat() if migration_time else None,
            json.dumps(features, sort_keys=True),
        ),
    )
    conn.commit()


async def write_snapshots(
    client: TelegramClient,
    conn: sqlite3.Connection,
    entity: Any,
    group_key: str,
    input_ref: str,
    windows: list[int],
    migration_time: Optional[datetime],
    burst_threshold: int,
) -> dict[str, Any]:
    member_count = await get_member_count(client, entity)
    save_group(conn, group_key, input_ref, entity, member_count)

    snapshots = [
        compute_window_features(
            conn=conn,
            group_key=group_key,
            lookback_minutes=window,
            member_count=member_count,
            end_time=None,
            migration_time=migration_time,
            burst_threshold=burst_threshold,
        )
        for window in windows
    ]

    for snapshot in snapshots:
        save_snapshot(conn, group_key, input_ref, entity, snapshot, migration_time)

    return {
        "group": getattr(entity, "title", None),
        "username": getattr(entity, "username", None),
        "group_key": group_key,
        "db_path": str(Path(conn.execute("PRAGMA database_list").fetchone()["file"]).resolve()),
        "collected_at_utc": utc_now().isoformat(),
        "snapshots": snapshots,
        "cross_window": add_cross_window_features(snapshots),
    }


