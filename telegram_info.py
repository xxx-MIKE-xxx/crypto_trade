URL_RE = re.compile(
    r"(https?://|t\.me/|dexscreener\.com|birdeye\.so|pump\.fun|raydium\.io|jup\.ag|x\.com|twitter\.com)",
    re.IGNORECASE,
)
DOMAIN_RE = re.compile(r"(?:https?://)?(?:www\.)?([a-z0-9.-]+\.[a-z]{2,})(?:/|\b)", re.IGNORECASE)
SOLANA_ADDR_RE = re.compile(r"\b[1-9A-HJ-NP-Za-km-z]{32,44}\b")
CASHTAG_RE = re.compile(r"\$[A-Za-z][A-Za-z0-9_]{1,16}")
BOT_COMMAND_RE = re.compile(r"^/[A-Za-z0-9_]+(?:@\w+)?\b")
WHITESPACE_RE = re.compile(r"\s+")

# Trade-alert messages are often generated by buy/sell bots. We keep them as
# volume proxies but remove them from human/community quality metrics.
TRADE_BUY_RE = re.compile(
    r"(?:🟢|🟩|✅|\bnew\s+buy\b|\bbuy!\b|\bbought\b|\baped\b|\bape\s+in\b)",
    re.IGNORECASE,
)
TRADE_SELL_RE = re.compile(
    r"(?:🔴|🟥|❌|\bnew\s+sell\b|\bsell!\b|\bsold\b)",
    re.IGNORECASE,
)
TRADE_CONTEXT_RE = re.compile(
    r"\b(?:sol|usdc|usd|market\s*cap|mcap|fdv|price|tx|txn|transaction|chart|dex|"
    r"pump\.fun|raydium|jupiter|birdeye|dexscreener|tokens?|holders?|wallet|spent|got)\b",
    re.IGNORECASE,
)
TRADE_NUMERIC_RE = re.compile(r"(?:\d+(?:\.\d+)?\s*(?:sol|usdc|usd|\$)|\$\s*\d+)", re.IGNORECASE)


